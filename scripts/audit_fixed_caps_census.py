    lr = LocalReader(texts, gr.s, gr, defines, rows)
    lines_of, out = {}, []
    for r in rows:
        if r[2] != "local":
            out.append(tuple(r) + ("",))
            continue
        if r[0] not in lines_of:
            lines_of[r[0]] = texts[r[0]].split("\n")
        i = int(r[1])
        c = is_const_table(lines_of[r[0]][i - 1] if 0 < i <= len(lines_of[r[0]]) else "", r[3])
