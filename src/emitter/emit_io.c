#include "emit.h"
#include <stdarg.h>
#include <stdlib.h>
#include <string.h>
static FILE *          g_emit_sink = NULL;
/*----------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------*/
void emit_io_set_sink(FILE * out) { g_emit_sink = out; }
/*----------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------*/
void emit_text_n(const char * s, size_t n) {
    if (!s || n == 0) return;
    if (g_emit_sink) fwrite(s, 1, n, g_emit_sink);
}
